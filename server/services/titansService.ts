export function getTitanMasterById(id: string): TitanMaster | null {
  return titansState.find((t) => t.id === id) || null;
}

export function resetTitanLedger(titanId: string, capital: number = 25000.0): TitanMaster | null {
  const titan = titansState.find((t) => t.id === titanId);
  if (!titan) return null;

  titan.sub_ledger = {
    strategy_id: titan.id,
    strategy_name: titan.sub_ledger.strategy_name,
    category: titan.sub_ledger.category,
    categoryLabel: titan.sub_ledger.categoryLabel,
    initial_capital: capital,
    liquid_cash: capital,
    invested_capital: 0,
    total_equity: capital,
    realized_pnl: 0,
    unrealized_pnl: 0,
    net_return_rupees: 0,
    net_return_pct: 0,
    win_rate_pct: titan.sub_ledger.win_rate_pct,
    profit_factor: titan.sub_ledger.profit_factor,
    sharpe_ratio: titan.sub_ledger.sharpe_ratio,
    max_drawdown_pct: 0,
    trade_count: 0,
    winning_trades: 0,
    losing_trades: 0,
    is_active_24_7: true,
    status: "ACTIVE_PAPER",
    last_evaluated_at: new Date().toISOString(),
    last_action_summary: `Titan ledger reset to pristine state with ₹${capital.toLocaleString("en-IN")}.`,
    active_holdings: [],
    closed_trades: [],
    equity_curve: [{ timestamp: new Date().toISOString(), equity: capital, cash: capital }],
  };

  dbSaveStrategyLedger(titan.sub_ledger);
  return titan;
}

/**
 * Evaluates all Titans against live quotes in real-time
 */
export async function evaluateTitanMastersLive(): Promise<TitanMaster[]> {
  for (const titan of titansState) {
    if (!titan.sub_ledger || !titan.sub_ledger.active_holdings) continue;

    for (let i = titan.sub_ledger.active_holdings.length - 1; i >= 0; i--) {
      const holding = titan.sub_ledger.active_holdings[i];
      try {
        const quote = await fetchRealtimeLivePrice(holding.ticker);
        if (quote && quote.current_price > 0) {
          holding.current_price = quote.current_price;
          const pnl = Number(((quote.current_price - holding.entry_fill_price) * holding.shares).toFixed(2));
          holding.unrealized_pnl = pnl;
          holding.unrealized_pnl_pct = Number(((pnl / (holding.entry_fill_price * holding.shares)) * 100).toFixed(2));

          // Target Hit
          if (holding.target_price > 0 && quote.current_price >= holding.target_price) {
            const closedValue = Number((holding.shares * quote.current_price).toFixed(2));
            titan.sub_ledger.liquid_cash = Number((titan.sub_ledger.liquid_cash + closedValue).toFixed(2));
            titan.sub_ledger.realized_pnl = Number((titan.sub_ledger.realized_pnl + pnl).toFixed(2));
            titan.sub_ledger.winning_trades = (titan.sub_ledger.winning_trades || 0) + 1;
            titan.sub_ledger.trade_count = (titan.sub_ledger.trade_count || 0) + 1;

            const closeRecord = {
              id: Date.now() + i,
              ticker: holding.ticker,
              bias: "BULLISH" as const,
              action: "BUY" as const,
              shares: holding.shares,
              entry_price: holding.entry_fill_price,
              exit_price: quote.current_price,
              pnl_realized: pnl,
              pnl_pct: holding.unrealized_pnl_pct,
              lesson: `[Master: ${titan.name}] Target achieved at ₹${quote.current_price} (+₹${pnl}).`,
              timestamp: new Date().toISOString(),
              execution_mode: "PAPER",
              strategy_id: titan.id,
              strategy_name: titan.name,
            };
            titan.sub_ledger.closed_trades.unshift(closeRecord);
            dbSaveTradeHistory(closeRecord);

            titan.sub_ledger.active_holdings.splice(i, 1);
            titan.sub_ledger.last_action_summary = `Take-profit booked on ${holding.ticker} (+₹${pnl}). Isolated balance: ₹${titan.sub_ledger.liquid_cash}.`;
          }
          // Stop Loss Hit
          else if (holding.stop_loss > 0 && quote.current_price <= holding.stop_loss) {
            const closedValue = Number((holding.shares * quote.current_price).toFixed(2));
            titan.sub_ledger.liquid_cash = Number((titan.sub_ledger.liquid_cash + closedValue).toFixed(2));
            titan.sub_ledger.realized_pnl = Number((titan.sub_ledger.realized_pnl + pnl).toFixed(2));
            titan.sub_ledger.losing_trades = (titan.sub_ledger.losing_trades || 0) + 1;
            titan.sub_ledger.trade_count = (titan.sub_ledger.trade_count || 0) + 1;

            const closeRecord = {
              id: Date.now() + i,
              ticker: holding.ticker,
              bias: "BULLISH" as const,
              action: "BUY" as const,
              shares: holding.shares,
              entry_price: holding.entry_fill_price,
              exit_price: quote.current_price,
              pnl_realized: pnl,
              pnl_pct: holding.unrealized_pnl_pct,
              lesson: `[Master: ${titan.name}] Defensive stop executed at ₹${quote.current_price} (-₹${Math.abs(pnl)}). Capital protected.`,
              timestamp: new Date().toISOString(),
              execution_mode: "PAPER",
              strategy_id: titan.id,
              strategy_name: titan.name,
            };
            titan.sub_ledger.closed_trades.unshift(closeRecord);
            dbSaveTradeHistory(closeRecord);

            titan.sub_ledger.active_holdings.splice(i, 1);
            titan.sub_ledger.last_action_summary = `Stop loss executed on ${holding.ticker} (-₹${Math.abs(pnl)}). Capital preserved.`;
          }
        }
      } catch (_) {}
    }

    // Recompute totals
    const invested = titan.sub_ledger.active_holdings.reduce((sum, h) => sum + h.entry_fill_price * h.shares, 0);
    const holdingsVal = titan.sub_ledger.active_holdings.reduce((sum, h) => sum + h.current_price * h.shares, 0);
    const unrealized = Number((holdingsVal - invested).toFixed(2));
    const totalEquity = Number((titan.sub_ledger.liquid_cash + holdingsVal).toFixed(2));
    const netReturn = Number((totalEquity - titan.sub_ledger.initial_capital).toFixed(2));
    const netReturnPct = Number(((netReturn / titan.sub_ledger.initial_capital) * 100).toFixed(2));

    titan.sub_ledger.invested_capital = Number(invested.toFixed(2));
    titan.sub_ledger.unrealized_pnl = unrealized;
    titan.sub_ledger.total_equity = totalEquity;
    titan.sub_ledger.net_return_rupees = netReturn;
    titan.sub_ledger.net_return_pct = netReturnPct;
    titan.sub_ledger.last_evaluated_at = new Date().toISOString();

    dbSaveStrategyLedger(titan.sub_ledger);
  }

  return titansState;
}
